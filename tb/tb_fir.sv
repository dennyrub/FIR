`timescale 1ns / 1ps // Указываем единицы времени: 1 нс, точность 1 пс

module tb_fir;

    // ==========================================
    // 1. Объявление сигналов (провода для DUT)
    // ==========================================
    logic clk;
    logic rst_n;
    logic signed [15:0] x;
    logic signed [15:0] y;

    // Массив коэффициентов (для DUT)
    localparam logic signed [15:0] COEF = 16'sd32767;
    logic signed [15:0] h [8];

    // ==========================================
    // 2. Память для векторов (входные и эталонные)
    // ==========================================
    // Размер 1030 берем из вывода python-скрипта
    logic signed [15:0] x_mem [1030];
    logic signed [15:0] y_mem [1030];

    // ==========================================
    // 3. Генератор тактового сигнала
    // ==========================================
    initial clk = 0;
    always #5 clk <= ~clk; // Период 10 нс (скважность 2)

    // ==========================================
    // 4. Блок инициализации (чтение файлов и h)
    // ==========================================
    initial begin
        // Читаем hex-файлы. Путь считается от папки, ОТКУДА ЗАПУСКАЕТСЯ СИМУЛЯЦИЯ.
        // Если запускать из корня FIR/, то пути будут такими:
        $readmemh("vectors/x.hex", x_mem);
        $readmemh("vectors/y.hex", y_mem);
        $display("ЧТЕНИЕ ФАЙЛОВ: x_mem[0]=%h, y_mem[0]=%h", x_mem[0], y_mem[0]);

        // Заполняем коэффициенты
        for (int i = 0; i < 8; i++) begin
            h[i] = 16'(COEF);
        end
    end

    // ==========================================
    // 5. Блок сброса (Reset)
    // ==========================================
    initial begin
        rst_n = 0; // Держим сброс
        x = 0; // Входной сигнал в нуле
        repeat (4) @(posedge clk); // Ждем 4 такта (стандарт)
        rst_n = 1; // Отпускаем сброс
    end

    // ==========================================
    // 6. Основной блок подачи данных и проверки
    // ==========================================
    initial begin
        int errors = 0;

        // Ждем, пока сброс отпустится (ожидаем фронт rst_n)
        wait (rst_n == 1);

        // TODO: Здесь пишется ваша логика из Шага 2.
        // 1. Цикл for от 0 до 1029.
        // 2. Подача x_mem[k] по negedge.
        // 3. Проверка y по negedge (сравнение с y_mem[k-1]).
        // 4. Вывод ошибки через $display, если есть.

        @(negedge clk);
        x = x_mem[0];

        // Основной цикл (начинаем проверку с i=2, так как нужно 2 такта на конвейер)
        for (int i = 1; i < 1030; i++) begin
            @(negedge clk);
            x = x_mem[i];

            if (i >= 2) begin
                if ($signed(y) !== $signed(y_mem[i-2])) begin
                    if (errors < 5) begin // Печатаем только первые 5 ошибок
                        $display("ОШИБКА: i=%0d, Ожид: %0d, Получ: %0d", i-2, $signed(y_mem[i-2]), $signed(y));
                    end
                    errors++;
                end
            end
        end

        // Досчитываем хвост конвейера (2 последних отсчета)
        @(negedge clk);
        x = 0;
        if ($signed(y) !== $signed(y_mem[1028])) begin
            $display("ОШИБКА в хвосте: Ожид: %0d, Получ: %0d", $signed(y_mem[1028]), $signed(y));
            errors++;
        end

        @(negedge clk);
        x = 0;
        if ($signed(y) !== $signed(y_mem[1029])) begin
            $display("ОШИБКА в хвосте: Ожид: %0d, Получ: %0d", $signed(y_mem[1029]), $signed(y));
            errors++;
        end
        // Вывод результата
        if (errors == 0) $display("=== PASS: Все тесты пройдены! ===");
        else $display("=== FAIL: %0d ошибок ===", errors);
        $finish; // Завершаем симуляцию
    end

    // ==========================================
    // 7. Таймаут (страховка от зависаний)
    // ==========================================
    initial begin
        #200000; // Ждем 200 мкс (это ~20000 тактов, с запасом)
        $display("TIMEOUT: симуляция зависла!");
        $finish; // Принудительно завершаем
    end

    // ==========================================
    // 8. Инстанс проверяемого модуля (DUT)
    // ==========================================
    fir dut (
        .clk (clk),
        .rst_n (rst_n),
        .x (x),
        .h (h),
        .y (y)
    );

endmodule





